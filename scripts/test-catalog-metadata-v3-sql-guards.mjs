import assert from 'node:assert/strict'
import fs from 'node:fs'
const staging=fs.readFileSync(new URL('./catalog-metadata-v3-staging.sql',import.meta.url),'utf8').toLowerCase()
const writer=fs.readFileSync(new URL('./catalog-metadata-v3-atomic-write-DRAFT.sql',import.meta.url),'utf8').toLowerCase()
assert.match(staging,/enable row level security/)
assert.match(staging,/revoke all on table public\.catalog_product_metadata_v3 from anon, authenticated/)
assert.match(staging,/grant select on table public\.catalog_product_metadata_v3 to authenticated/)
assert.doesNotMatch(staging,/grant select, insert, update, delete/)
assert.match(staging,/p-'image'-'imagedata'-'photo'/)
assert.match(writer,/language plpgsql security invoker set search_path = ''/)
assert.match(writer,/p_payload \?\| array\['image','imagedata','photo'\]/)
assert.match(writer,/where id=p_id and updated_at=p_expected_updated_at/g)
assert.match(writer,/if p_action='delete' then\s+delete from public\.catalog_product_images/)
assert.match(writer,/elsif p_image is not null then/)
assert.match(writer,/where public\.catalog_product_images\.image is distinct from excluded\.image/)
assert.match(writer,/revoke all on function public\.mutate_catalog_metadata_v3/)
assert.match(writer,/grant execute on function public\.mutate_catalog_metadata_v3.*to authenticated/)
assert.doesNotMatch(writer,/(update|delete from) public\.app_state/)
assert.doesNotMatch(writer,/(update|delete from) public\.public_catalog/)
console.log('OK: image-free metadata staging and RPC respect row CAS, RLS, conditional image writes')
