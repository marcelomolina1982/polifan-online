import fs from 'node:fs'
import assert from 'node:assert/strict'

const sql=fs.readFileSync(new URL('./catalog-image-externalization-TRIGGER-DRAFT.sql',import.meta.url),'utf8')
assert.match(sql,/DRAFT — DO NOT APPLY UNTIL/)
assert.equal((sql.match(/^commit;$/gm)||[]).length,1,'A draft must have exactly one COMMIT')
assert.equal((sql.match(/create trigger zz_compact_main_catalog_images_before_write/g)||[]).length,1,'Do not install duplicate triggers')
assert.match(sql,/elsif image_text is null or image_text = '' then/)
assert.match(sql,/select i.updated_at into image_revision/)
assert.ok(sql.includes("v_product_id !~ '^[A-Za-z0-9._~-]+$' then"))
assert.match(sql,/alter table public\\.app_state add column if not exists catalog_write_nonce uuid/)
assert.match(sql,/new\\.catalog_write_nonce is not distinct from old\\.catalog_write_nonce/)
assert.match(sql,/security invoker/)
assert.match(sql,/set search_path = ''/)
assert.match(sql,/before update of data on public\.app_state/)
assert.match(sql,/for each row when \(new\.id='main'\)/)
assert.match(sql,/new\.data := pg_catalog\.jsonb_set\(new\.data,'\{customerCatalog\}',compact_products\)/)
assert.match(sql,/existing_image is distinct from image_text/)
assert.match(sql,/on conflict \(product_id\)/)
assert.match(sql,/where public\.catalog_product_images\.image is distinct from excluded\.image/)
assert.match(sql,/image_url := 'https:\/\/eftksimpkkvmyfurwqii\.supabase\.co\/functions\/v1\/catalog-image\?id='/)
assert.match(sql,/&v=/)
assert.match(sql,/&rev=/)
assert.match(sql,/extract\(epoch from image_revision\)/)
assert.match(sql,/v_product_id !~ '\^\[A-Za-z0-9\._~-\]\+\$'/)
assert.doesNotMatch(sql,/pg_catalog\.extract\(/)
assert.doesNotMatch(sql,/pg_catalog\.greatest\(/)
assert.doesNotMatch(sql,/(delete from public\.app_state|truncate.*app_state|drop table)/i)
assert.doesNotMatch(sql,/update public\.public_catalog/)
assert.match(sql,/if not exists\(/)
assert.match(sql,/if image_revision is null then\s+raise exception 'Image was not safely persisted'/)

// A dry-run must never use public business tables. Derive it from the exact
// draft rather than maintaining an untested second copy of its function.
const start=sql.indexOf('\nbegin;\n')
const end=sql.indexOf('\ncommit;',start)
assert.ok(start>=0&&end>start)
const temp=sql.slice(start+8,end)
  .replaceAll('public.catalog_product_images','pg_temp.catalog_product_images')
  .replaceAll('public.app_state','pg_temp.app_state')
  .replaceAll('public.compact_main_catalog_images_before_write','pg_temp.compact_main_catalog_images_before_write')
assert.doesNotMatch(temp,/public\.(app_state|catalog_product_images|compact_main_catalog_images_before_write)/)
assert.match(temp,/pg_temp\.app_state/)
assert.match(temp,/pg_temp\.catalog_product_images/)
console.log('OK: legacy-compatible image compact trigger has atomic image writes and safe pg_temp dry-run mapping')
